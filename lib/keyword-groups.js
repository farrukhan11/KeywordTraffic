export function normalizeKeyword(value) {
  return String(value || "").trim().replace(/\s+/g, " ");
}

export function groupKey(name) {
  return normalizeKeyword(name).toLowerCase();
}

function isTrailingModifier(token) {
  return MODIFIER_WORDS.has(normalizeModifierToken(token));
}

export function deriveGroupName(keyword) {
  const tokens = normalizeKeyword(keyword).split(" ").filter(Boolean);
  while (tokens.length > 1 && isTrailingModifier(tokens[tokens.length - 1])) {
    tokens.pop();
  }
  return tokens.join(" ").trim();
}

export function buildRequestedGroups(keywords) {
  const groups = [];
  const byKey = new Map();
  const keywordToGroupKey = new Map();

  (Array.isArray(keywords) ? keywords : []).forEach((keyword) => {
    const normalized = normalizeKeyword(keyword);
    if (!normalized) return;

    const name = deriveGroupName(normalized) || normalized;
    const key = groupKey(name);

    let group = byKey.get(key);
    if (!group) {
      group = { key, name, requestedKeywords: [] };
      byKey.set(key, group);
      groups.push(group);
    }

    group.requestedKeywords.push(keyword);
    keywordToGroupKey.set(normalized.toLowerCase(), key);
  });

  return { groups, byKey, keywordToGroupKey };
}

export function resolveResultGroupKey(result, keywordToGroupKey) {
  const keyword = normalizeKeyword(result?.keyword).toLowerCase();
  if (keywordToGroupKey.has(keyword)) return keywordToGroupKey.get(keyword);

  const closeVariants = Array.isArray(result?.closeVariants) ? result.closeVariants : [];
  for (const variant of closeVariants) {
    const variantKey = normalizeKeyword(variant).toLowerCase();
    if (keywordToGroupKey.has(variantKey)) return keywordToGroupKey.get(variantKey);
  }

  const name = deriveGroupName(result?.keyword) || normalizeKeyword(result?.keyword);
  return groupKey(name);
}
