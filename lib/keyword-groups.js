function normalizeModifierToken(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/đ/g, "d")
    .replace(/ı/g, "i")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\p{L}\p{N}]+/gu, "");
}

